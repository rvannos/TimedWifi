import os
import subprocess
import logging
import time
from pathlib import Path
from typing import Dict, Any, List, Optional

logger = logging.getLogger("hotspot.network")

DNSMASQ_CONF_PATH = "/tmp/dnsmasq_hotspot.conf"
DNSMASQ_LEASES_PATH = "/var/lib/misc/dnsmasq.leases"
HOSTAPD_CONF_PATH = "/tmp/hostapd.conf"


class NetworkDriver:
    def __init__(self):
        self.hotspot_active: bool = False
        self.mock_allowed_ips: set[str] = set()
        self.last_command_logs: List[Dict[str, Any]] = []

    def _log_cmd(self, cmd: str, mock: bool, rc: int = 0, out: str = ""):
        entry = {
            "timestamp": time.time(),
            "cmd": cmd,
            "mock": mock,
            "rc": rc,
            "output": out[:200],
        }
        self.last_command_logs.insert(0, entry)
        if len(self.last_command_logs) > 50:
            self.last_command_logs.pop()

    def _run(self, cmd: List[str], mock: bool = True, check: bool = False, log: bool = True) -> subprocess.CompletedProcess:
        cmd_str = " ".join(cmd)
        if mock:
            logger.info("[MOCK] Executing: %s", cmd_str)
            if log:
                self._log_cmd(cmd_str, mock=True, rc=0, out="Simulated OK")
            return subprocess.CompletedProcess(args=cmd, returncode=0, stdout="MOCK_OK", stderr="")
        try:
            logger.info("[LIVE] Executing: %s", cmd_str)
            res = subprocess.run(cmd, capture_output=True, text=True, timeout=15)
            if log:
                self._log_cmd(cmd_str, mock=False, rc=res.returncode, out=(res.stdout or res.stderr).strip())
            if check and res.returncode != 0:
                logger.error("Command failed (%d): %s -> %s", res.returncode, cmd_str, res.stderr)
            return res
        except Exception as exc:
            logger.exception("Command execution error: %s", cmd_str)
            if log:
                self._log_cmd(cmd_str, mock=False, rc=-1, out=str(exc))
            return subprocess.CompletedProcess(args=cmd, returncode=-1, stdout="", stderr=str(exc))

    def detect_interfaces(self) -> List[str]:
        ifaces = []
        try:
            net_dir = Path("/sys/class/net")
            if net_dir.exists():
                for item in sorted(net_dir.iterdir()):
                    if item.name != "lo":
                        ifaces.append(item.name)
        except Exception:
            pass
        # Append fallback placeholder names only if needed
        for std in ["wlan0", "eth0", "eth1"]:
            if std not in ifaces:
                ifaces.append(std)
        return ifaces

    def generate_dnsmasq_conf(self, settings: Dict[str, Any]) -> str:
        lan_iface = settings.get("lan_iface", "wlp82s0")
        gw_ip = settings.get("gateway_ip", "192.168.4.1")
        dhcp_start = settings.get("dhcp_start", "192.168.4.10")
        dhcp_end = settings.get("dhcp_end", "192.168.4.200")

        conf = f"""# Auto-generated by School Event Timed Hotspot Controller
interface={lan_iface}
bind-dynamic
except-interface=lo
listen-address={gw_ip}
dhcp-range={dhcp_start},{dhcp_end},255.255.255.0,12h
dhcp-option=3,{gw_ip}
dhcp-option=6,{gw_ip}
dhcp-option=114,http://{gw_ip}:8000/portal
dhcp-leasefile={DNSMASQ_LEASES_PATH}
server=8.8.8.8
server=1.1.1.1
log-queries
log-dhcp
"""
        Path(DNSMASQ_CONF_PATH).write_text(conf, encoding="utf-8")
        return DNSMASQ_CONF_PATH

    def generate_hostapd_conf(self, settings: Dict[str, Any]) -> str:
        lan_iface = settings.get("lan_iface", "wlp82s0")
        ssid = settings.get("ssid", "School_Event_Pay")
        channel = settings.get("wifi_channel", 6)
        wpa_pass = settings.get("wpa_passphrase", "").strip()

        conf = f"""# Auto-generated by School Event Timed Hotspot Controller
interface={lan_iface}
driver=nl80211
ssid={ssid}
hw_mode=g
channel={channel}
wmm_enabled=1
macaddr_acl=0
auth_algs=1
ignore_broadcast_ssid=0
"""
        if wpa_pass and len(wpa_pass) >= 8:
            conf += f"""wpa=2
wpa_passphrase={wpa_pass}
wpa_key_mgmt=WPA-PSK
wpa_pairwise=TKIP
rsn_pairwise=CCMP
"""
        Path(HOSTAPD_CONF_PATH).write_text(conf, encoding="utf-8")
        return HOSTAPD_CONF_PATH

    def start_hotspot(self, settings: Dict[str, Any], allowed_ips: List[str] = None) -> Dict[str, Any]:
        mock = bool(settings.get("mock_network", True))
        mode = settings.get("mode", "Mode A")
        wan_iface = settings.get("wan_iface", "enx3c18a0d3d673")
        lan_iface = settings.get("lan_iface", "wlp82s0")
        gw_ip = settings.get("gateway_ip", "192.168.4.1")

        # 1. Generate configs
        self.generate_dnsmasq_conf(settings)
        if mode == "Mode A":
            self.generate_hostapd_conf(settings)

        # 2. Stop existing instances cleanly
        self._run(["sudo", "/usr/bin/pkill", "-f", DNSMASQ_CONF_PATH], mock=mock, log=False)
        self._run(["sudo", "/usr/bin/pkill", "-f", HOSTAPD_CONF_PATH], mock=mock, log=False)

        # 3. Hand off LAN interface from Ubuntu NetworkManager so it doesn't wipe 192.168.4.1 or fight hostapd
        self._run(["/usr/bin/nmcli", "dev", "set", lan_iface, "managed", "no"], mock=mock)
        if mode == "Mode A":
            self._run(["/usr/sbin/rfkill", "unblock", "wifi"], mock=mock)

        # 4. Configure LAN interface IP
        self._run(["sudo", "/sbin/ip", "addr", "flush", "dev", lan_iface], mock=mock)
        self._run(["sudo", "/sbin/ip", "addr", "add", f"{gw_ip}/24", "dev", lan_iface], mock=mock)
        self._run(["sudo", "/sbin/ip", "link", "set", lan_iface, "up"], mock=mock)

        # 5. Enable IPv4 forwarding
        self._run(["sudo", "/sbin/sysctl", "-w", "net.ipv4.ip_forward=1"], mock=mock)

        # 6. Start hostapd ONLY in Mode A
        if mode == "Mode A":
            self._run(["sudo", "/usr/sbin/hostapd", "-B", HOSTAPD_CONF_PATH], mock=mock)
            if not mock:
                time.sleep(0.5)
            self._run(["sudo", "/sbin/ip", "addr", "replace", f"{gw_ip}/24", "dev", lan_iface], mock=mock)
            self._run(["sudo", "/sbin/ip", "link", "set", lan_iface, "up"], mock=mock)

        # 7. Start dnsmasq (uses /var/lib/misc/dnsmasq.leases to satisfy Ubuntu AppArmor)
        self._run(["sudo", "/usr/sbin/dnsmasq", "-C", DNSMASQ_CONF_PATH], mock=mock)

        # 8. Configure iptables Captive Portal & NAT
        self.setup_firewall(settings, allowed_ips or [])

        # 9. Configure bandwidth limiting if enabled
        self.apply_bandwidth_limit(settings)

        self.hotspot_active = True
        return self.get_service_status(settings)

    def stop_hotspot(self, settings: Dict[str, Any]) -> Dict[str, Any]:
        mock = bool(settings.get("mock_network", True))
        lan_iface = settings.get("lan_iface", "wlp82s0")
        wan_iface = settings.get("wan_iface", "enx3c18a0d3d673")

        self._run(["sudo", "/usr/bin/pkill", "-f", DNSMASQ_CONF_PATH], mock=mock)
        self._run(["sudo", "/usr/bin/pkill", "-f", HOSTAPD_CONF_PATH], mock=mock)
        self._run(["sudo", "/sbin/iptables", "-F", "FORWARD"], mock=mock)
        self._run(["sudo", "/sbin/iptables", "-t", "nat", "-F", "PREROUTING"], mock=mock)
        self._run(["sudo", "/sbin/iptables", "-t", "nat", "-D", "POSTROUTING", "-o", wan_iface, "-j", "MASQUERADE"], mock=mock, log=False)

        # Return LAN interface back to Ubuntu NetworkManager
        self._run(["sudo", "/sbin/ip", "addr", "flush", "dev", lan_iface], mock=mock)
        self._run(["/usr/bin/nmcli", "dev", "set", lan_iface, "managed", "yes"], mock=mock)

        if not mock:
            subprocess.run(["sudo", "/usr/sbin/tc", "qdisc", "del", "dev", lan_iface, "root"], capture_output=True)

        self.hotspot_active = False
        return self.get_service_status(settings)

    def setup_firewall(self, settings: Dict[str, Any], allowed_ips: List[str]):
        mock = bool(settings.get("mock_network", True))
        wan_iface = settings.get("wan_iface", "eth0")
        lan_iface = settings.get("lan_iface", "wlan0")
        gw_ip = settings.get("gateway_ip", "192.168.4.1")

        # Flush FORWARD and nat PREROUTING to ensure clean state
        self._run(["sudo", "/sbin/iptables", "-F", "FORWARD"], mock=mock)
        self._run(["sudo", "/sbin/iptables", "-t", "nat", "-F", "PREROUTING"], mock=mock)

        # NAT Masquerade on WAN
        self._run(["sudo", "/sbin/iptables", "-t", "nat", "-A", "POSTROUTING", "-o", wan_iface, "-j", "MASQUERADE"], mock=mock)

        # Allow established/related back to clients
        self._run(["sudo", "/sbin/iptables", "-A", "FORWARD", "-i", wan_iface, "-o", lan_iface, "-m", "state", "--state", "RELATED,ESTABLISHED", "-j", "ACCEPT"], mock=mock)
        # Allow DNS queries
        self._run(["sudo", "/sbin/iptables", "-A", "FORWARD", "-i", lan_iface, "-p", "udp", "--dport", "53", "-j", "ACCEPT"], mock=mock)
        self._run(["sudo", "/sbin/iptables", "-A", "FORWARD", "-i", lan_iface, "-p", "tcp", "--dport", "53", "-j", "ACCEPT"], mock=mock)
        # Default drop unauthenticated forwarding from LAN
        self._run(["sudo", "/sbin/iptables", "-A", "FORWARD", "-i", lan_iface, "-j", "DROP"], mock=mock)

        # Redirect unauthenticated HTTP (port 80) to local Captive Portal (192.168.4.1:8000)
        self._run([
            "sudo", "/sbin/iptables", "-t", "nat", "-A", "PREROUTING",
            "-i", lan_iface, "-p", "tcp", "--dport", "80",
            "-j", "DNAT", "--to-destination", f"{gw_ip}:8000"
        ], mock=mock)

        self.mock_allowed_ips.clear()
        for ip in allowed_ips:
            self.authorize_client(ip, settings)

    def authorize_client(self, client_ip: str, settings: Dict[str, Any]):
        mock = bool(settings.get("mock_network", True))
        gw_ip = settings.get("gateway_ip", "192.168.4.1")
        lan_iface = settings.get("lan_iface", "wlan0")

        if client_ip in self.mock_allowed_ips and mock:
            return

        # Delete first to avoid duplicate entries in live mode
        if not mock:
            self._run(["sudo", "/sbin/iptables", "-D", "FORWARD", "-s", client_ip, "-j", "ACCEPT"], mock=False, log=False)
            self._run(["sudo", "/sbin/iptables", "-t", "nat", "-D", "PREROUTING", "-i", lan_iface, "-s", client_ip, "-j", "ACCEPT"], mock=False, log=False)

        # Exact specification rule: Insert -I FORWARD 1 -s <CLIENT_IP> -j ACCEPT
        self._run(["sudo", "/sbin/iptables", "-I", "FORWARD", "1", "-s", client_ip, "-j", "ACCEPT"], mock=mock)
        # Also bypass captive portal NAT redirect for authorized client
        self._run(["sudo", "/sbin/iptables", "-t", "nat", "-I", "PREROUTING", "1", "-i", lan_iface, "-s", client_ip, "-j", "ACCEPT"], mock=mock)
        self.mock_allowed_ips.add(client_ip)

    def revoke_client(self, client_ip: str, settings: Dict[str, Any]):
        mock = bool(settings.get("mock_network", True))
        lan_iface = settings.get("lan_iface", "wlan0")

        # Exact specification rule: Delete the rule -D FORWARD -s <CLIENT_IP> -j ACCEPT
        self._run(["sudo", "/sbin/iptables", "-D", "FORWARD", "-s", client_ip, "-j", "ACCEPT"], mock=mock)
        self._run(["sudo", "/sbin/iptables", "-t", "nat", "-D", "PREROUTING", "-i", lan_iface, "-s", client_ip, "-j", "ACCEPT"], mock=mock)
        self.mock_allowed_ips.discard(client_ip)

    def apply_bandwidth_limit(self, settings: Dict[str, Any]):
        mock = bool(settings.get("mock_network", True))
        lan_iface = settings.get("lan_iface", "wlan0")
        enabled = bool(settings.get("bandwidth_limit_enabled", False))
        mbps = int(settings.get("bandwidth_limit_mbps", 5))

        if mock:
            if enabled:
                self._log_cmd(f"tc qdisc replace dev {lan_iface} root tbf rate {mbps}mbit burst 32kbit latency 400ms", mock=True)
            else:
                self._log_cmd(f"tc qdisc del dev {lan_iface} root", mock=True)
            return

        subprocess.run(["sudo", "/usr/sbin/tc", "qdisc", "del", "dev", lan_iface, "root"], capture_output=True)
        if enabled:
            subprocess.run([
                "sudo", "/usr/sbin/tc", "qdisc", "add", "dev", lan_iface,
                "root", "tbf", "rate", f"{mbps}mbit", "burst", "32kbit", "latency", "400ms"
            ], capture_output=True)

    def read_dhcp_leases(self, settings: Dict[str, Any]) -> List[Dict[str, str]]:
        leases = []
        lease_file = Path(DNSMASQ_LEASES_PATH)
        if lease_file.exists():
            try:
                for line in lease_file.read_text(encoding="utf-8").splitlines():
                    parts = line.strip().split()
                    if len(parts) >= 4:
                        # Format: <timestamp> <mac> <ip> <hostname> <client-id>
                        leases.append({
                            "mac": parts[1].upper(),
                            "ip": parts[2],
                            "hostname": parts[3] if parts[3] != "*" else "Guest-Device",
                        })
            except Exception as e:
                logger.warning("Failed reading dnsmasq leases: %s", e)
        return leases

    def get_service_status(self, settings: Dict[str, Any]) -> Dict[str, Any]:
        mock = bool(settings.get("mock_network", True))
        mode = settings.get("mode", "Mode A")

        if mock:
            return {
                "hotspot_active": self.hotspot_active,
                "mock_network": True,
                "mode": mode,
                "dnsmasq": "running (mock)" if self.hotspot_active else "stopped",
                "hostapd": ("disabled (external AP)" if mode != "Mode A" else ("running (mock)" if self.hotspot_active else "stopped")),
                "nat": "active (mock)" if self.hotspot_active else "inactive",
                "recent_commands": self.last_command_logs[:10],
            }

        # Live checks
        dns_res = subprocess.run(["pgrep", "-f", DNSMASQ_CONF_PATH], capture_output=True)
        dns_running = dns_res.returncode == 0

        if mode != "Mode A":
            hostapd_status = "disabled (external AP)"
        else:
            hap_res = subprocess.run(["pgrep", "-f", HOSTAPD_CONF_PATH], capture_output=True)
            hostapd_status = "running" if hap_res.returncode == 0 else "stopped"

        ipf_res = subprocess.run(["/sbin/sysctl", "-n", "net.ipv4.ip_forward"], capture_output=True, text=True)
        nat_active = ipf_res.stdout.strip() == "1" and self.hotspot_active

        return {
            "hotspot_active": self.hotspot_active,
            "mock_network": False,
            "mode": mode,
            "dnsmasq": "running" if dns_running else "stopped",
            "hostapd": hostapd_status,
            "nat": "active" if nat_active else "inactive",
            "recent_commands": self.last_command_logs[:10],
        }


network_driver = NetworkDriver()
